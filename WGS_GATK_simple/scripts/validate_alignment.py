#!/usr/bin/env python3

"""
Проверка совместимости готового BAM/CRAM с референсным геномом.

Скрипт используется, когда в WGS-пайплайн передаётся уже
выровненный BAM или CRAM вместо исходных FASTQ.

Перед дальнейшей обработкой необходимо убедиться, что:
    1. BAM/CRAM отсортирован по координатам.
    2. В заголовке присутствуют Read Groups (@RG).
    3. Идентификатор образца (SM) соответствует samples.tsv.
    4. Набор последовательностей (@SQ) совпадает с референсом.
    5. Длины последовательностей совпадают с референсом.
    6. MD5 последовательностей совпадают, если указаны
       одновременно в BAM/CRAM и словаре референса.

Проверка выполняется по заголовку BAM/CRAM с помощью samtools.

Скрипт не изменяет входной BAM/CRAM или референс.
Он не проверяет содержимое всех выравниваний.
"""

from __future__ import annotations

import subprocess
import sys

from pathlib import Path

from model import reference_dict_path


# ============================================================
# 1. Проверка совместимости BAM/CRAM с референсом
# ============================================================

def validate(path, sample, reference):
    """
    Проверить заголовок BAM/CRAM.

    Аргументы:
        path:       путь к проверяемому BAM/CRAM;
        sample:     ожидаемый идентификатор образца;
        reference:  путь к FASTA референсного генома.

    Возвращает:
        True, если все проверки пройдены.

    При обнаружении несоответствия вызывает ValueError.

    Для чтения заголовка используется samtools view -H.
    """

    # --------------------------------------------------------
    # 1.1. Определение путей к референсу и его индексу
    # --------------------------------------------------------

    # Преобразуем путь к FASTA в объект Path.
    ref = Path(reference)

    # Индекс FASTA имеет то же имя с дополнительным .fai.
    #
    # Пример:
    #   genome.fna
    #   genome.fna.fai
    index = ref.with_name(ref.name + ".fai")

    # --------------------------------------------------------
    # 1.2. Чтение последовательностей из .fai
    # --------------------------------------------------------

    # Формат строки .fai:
    #   NAME  LENGTH  OFFSET  LINEBASES  LINEWIDTH
    #
    # Для проверки нужны только:
    #   NAME   — название последовательности;
    #   LENGTH — длина последовательности.
    #
    # Создаём словарь:
    #   название последовательности -> длина
    #
    # Пример:
    #   {
    #       "CM187741.1": 150000000,
    #       "CM187742.1": 132000000,
    #   }
    #
    # Длины в примере условные.

    reference_lengths = {
        row.split("\t")[0]: int(row.split("\t")[1])
        for row in index.read_text().splitlines()
        if row.strip()
    }

    # --------------------------------------------------------
    # 1.3. Чтение словаря референса (.dict)
    # --------------------------------------------------------

    # GATK/Picard используют файл .dict, содержащий
    # информацию о последовательностях референса.
    #
    # Пример строки:
    #   @SQ SN:CM187741.1 LN:150000000 M5:...
    #
    # SN — название последовательности.
    # LN — длина последовательности.
    # M5 — MD5 последовательности (если присутствует).
    #
    # Сохраняем все поля @SQ для каждой последовательности.

    dictionary = {}

    for line in reference_dict_path(ref).read_text().splitlines():

        # Рассматриваем только строки последовательностей.
        if line.startswith("@SQ\t"):

            # Разделяем поля вида KEY:VALUE.
            # split(":", 1) разделяет только по первому
            # двоеточию, сохраняя остальные в значении.
            tags = dict(
                field.split(":", 1)
                for field in line.split("\t")[1:]
                if ":" in field
            )

            # Сохраняем информацию по названию последовательности.
            dictionary[tags["SN"]] = tags

    # --------------------------------------------------------
    # 1.4. Чтение заголовка BAM/CRAM
    # --------------------------------------------------------

    # samtools view:
    #   -H — вывести только заголовок;
    #   -T — указать референсный FASTA;
    #
    # -T особенно важен для CRAM, поскольку CRAM
    # может требовать референс для декодирования.
    #
    # subprocess.run запускает внешнюю программу.
    #
    # check=True:
    #   Python вызывает исключение, если samtools
    #   завершился с ненулевым кодом.
    #
    # capture_output=True:
    #   stdout и stderr сохраняются в объекте result.
    #
    # text=True:
    #   вывод обрабатывается как текст, а не bytes.

    result = subprocess.run(
        [
            "samtools",
            "view",
            "-H",
            "-T",
            str(ref),
            path,
        ],
        check=True,
        capture_output=True,
        text=True,
    )

    # --------------------------------------------------------
    # 1.5. Подготовка структур для разбора заголовка
    # --------------------------------------------------------

    # Множество идентификаторов образцов из @RG SM.
    sample_names = set()

    # Количество строк Read Group (@RG).
    read_group_count = 0

    # Словарь последовательностей из заголовка BAM/CRAM.
    # Ключ — название последовательности (SN).
    sequence_dictionary = {}

    # Тип сортировки, указанный в @HD SO.
    sort_order = None

    # --------------------------------------------------------
    # 1.6. Разбор заголовка BAM/CRAM
    # --------------------------------------------------------

    # Заголовок SAM состоит из строк с разными тегами:
    #
    # @HD — общая информация, включая порядок сортировки.
    # @SQ — сведения о референсных последовательностях.
    # @RG — сведения о Read Groups и образцах.
    # @PG — сведения об использованных программах.
    #
    # Нас интересуют @HD, @RG и @SQ.

    for line in result.stdout.splitlines():

        # Разделяем строку на поля по символу табуляции.
        fields = line.split("\t")

        # Преобразуем поля KEY:VALUE в словарь.
        tags = dict(
            field.split(":", 1)
            for field in fields[1:]
            if ":" in field
        )

        # ----------------------------------------------------
        # Проверка информации о сортировке (@HD)
        # ----------------------------------------------------

        # Пример:
        #   @HD VN:1.6 SO:coordinate
        #
        # SO:coordinate означает сортировку по координатам.
        if line.startswith("@HD\t"):
            sort_order = tags.get("SO")

        # ----------------------------------------------------
        # Чтение информации об образцах (@RG)
        # ----------------------------------------------------

        # Пример:
        #   @RG ID:lane1 SM:SRR35396908 LB:LIB001
        #
        # ID — идентификатор Read Group.
        # SM — идентификатор образца.
        # LB — идентификатор библиотеки.

        if line.startswith("@RG\t"):

            # Увеличиваем число найденных Read Groups.
            read_group_count += 1

            # Добавляем название образца в множество.
            # Если SM отсутствует, добавляется пустая строка.
            sample_names.add(tags.get("SM", ""))

        # ----------------------------------------------------
        # Чтение информации о последовательностях (@SQ)
        # ----------------------------------------------------

        # Пример:
        #   @SQ SN:CM187741.1 LN:150000000 M5:...
        #
        # SN — название последовательности.
        # LN — длина последовательности.
        # M5 — контрольная сумма MD5 (необязательное поле).

        if line.startswith("@SQ\t"):

            # Получаем название последовательности.
            name = tags.get("SN", "")

            # Одна последовательность не должна
            # встречаться несколько раз в заголовке.
            if name in sequence_dictionary:
                raise ValueError(
                    "Duplicate @SQ in input"
                )

            # Сохраняем поля последовательности.
            sequence_dictionary[name] = tags

    # --------------------------------------------------------
    # 1.7. Проверка сортировки BAM/CRAM
    # --------------------------------------------------------

    # Для дальнейшей обработки требуется BAM/CRAM,
    # отсортированный по координатам.
    #
    # Проверяется значение SO в заголовке @HD.
    # Фактический порядок всех выравниваний здесь
    # не проверяется.

    if sort_order != "coordinate":
        raise ValueError(
            f"{path}: expected @HD SO:coordinate, "
            f"got {sort_order}"
        )

    # --------------------------------------------------------
    # 1.8. Проверка идентификатора образца
    # --------------------------------------------------------

    # Должна существовать хотя бы одна строка @RG.
    #
    # Все Read Groups должны относиться к одному
    # ожидаемому образцу.
    #
    # Например:
    #   sample = SRR35396908
    #   @RG SM:SRR35396908
    #
    # Несколько Read Groups допускаются, если значение
    # SM во всех них одинаковое.

    if read_group_count == 0 or sample_names != {sample}:
        raise ValueError(
            f"{path}: @RG SM must equal {sample}, "
            f"got {sample_names}"
        )

    # --------------------------------------------------------
    # 1.9. Проверка набора референсных последовательностей
    # --------------------------------------------------------

    # Набор @SQ в BAM/CRAM должен полностью совпадать
    # с набором последовательностей референса из .fai.
    #
    # Сравнение множеств не учитывает порядок.
    #
    # Если BAM был выровнен на другой референс
    # или содержит другой набор последовательностей,
    # проверка завершится ошибкой.

    if set(sequence_dictionary) != set(reference_lengths):
        raise ValueError(
            f"{path}: @SQ contig set differs "
            "from selected reference"
        )

    # --------------------------------------------------------
    # 1.10. Проверка длин последовательностей и MD5
    # --------------------------------------------------------

    # Для каждой последовательности проверяем:
    #   1. Совпадает ли длина LN.
    #   2. Совпадает ли MD5, если он есть
    #      в обоих заголовках.
    #
    # Совпадение только названий и длин не гарантирует,
    # что референсные последовательности идентичны.

    for name, tags in sequence_dictionary.items():

        # ----------------------------------------------------
        # Проверка длины последовательности
        # ----------------------------------------------------

        # Получаем длину LN из заголовка BAM/CRAM.
        # При отсутствии LN используется -1.
        bam_length = int(tags.get("LN", "-1"))

        # Сравниваем с длиной в .fai.
        if bam_length != reference_lengths[name]:
            raise ValueError(
                f"{path}: reference length mismatch for {name}"
            )

        # ----------------------------------------------------
        # Проверка MD5 последовательности
        # ----------------------------------------------------

        # Получаем MD5 из словаря референса.
        reference_md5 = dictionary[name].get("M5")

        # Получаем MD5 из заголовка BAM/CRAM.
        bam_md5 = tags.get("M5")

        # Сравниваем MD5 только в том случае,
        # если обе контрольные суммы присутствуют.
        #
        # Если хотя бы одна отсутствует, сравнение
        # для этой последовательности пропускается.
        if (
            reference_md5
            and bam_md5
            and reference_md5 != bam_md5
        ):
            raise ValueError(
                f"{path}: reference MD5 differs for {name}"
            )

    # --------------------------------------------------------
    # 1.11. Результат проверки
    # --------------------------------------------------------

    # Все проверки заголовка завершились успешно.
    return True


# ============================================================
# 2. Запуск скрипта из командной строки
# ============================================================

if __name__ == "__main__":

    try:

        # Ожидаемые аргументы:
        #   1. Путь к BAM/CRAM.
        #   2. Идентификатор образца.
        #   3. Путь к референсному FASTA.
        #
        # Передаём первые три аргумента функции validate().
        validate(*sys.argv[1:4])

    except Exception as error:

        # При ошибке выводим сообщение в stderr
        # и завершаем программу с ненулевым кодом.
        sys.exit(f"ERROR: {error}")