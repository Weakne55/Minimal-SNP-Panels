#!/usr/bin/env python3

"""
Вывод названий и длин последовательностей (contigs)
из существующего индекса референсного генома (.fai).

Скрипт только читает файл .fai.
Не изменяет FASTA и не создаёт новые индексы.
"""

import argparse
from pathlib import Path


# ------------------------------------------------------------
# 1. Чтение аргументов командной строки
# ------------------------------------------------------------

# Создаём парсер аргументов.
parser = argparse.ArgumentParser(description=__doc__)

# Обязательный аргумент — путь к существующему индексу FASTA.
parser.add_argument(
    "reference_fai",
    help="Путь к файлу индекса референсного генома (.fai)"
)

# Получаем аргументы, переданные пользователем.
args = parser.parse_args()


# ------------------------------------------------------------
# 2. Проверка существования файла индекса
# ------------------------------------------------------------

# Преобразуем путь к объекту Path.
fai_path = Path(args.reference_fai)

# Проверяем, что файл существует.
# Если файл отсутствует, выводим ошибку и завершаем программу.
if not fai_path.is_file():
    parser.error(
        "Файл .fai не найден. "
        "Скрипт не создаёт индексы референсного генома."
    )


# ------------------------------------------------------------
# 3. Чтение и вывод информации о последовательностях
# ------------------------------------------------------------

# Заголовок таблицы результатов.
print("contig\tlength")

# В файле .fai каждая строка соответствует одной
# последовательности референсного генома.
#
# Формат строки .fai:
# 1. NAME       — название последовательности
# 2. LENGTH     — длина последовательности в нуклеотидах
# 3. OFFSET     — позиция начала последовательности в FASTA
# 4. LINEBASES  — число нуклеотидов в строке FASTA
# 5. LINEWIDTH  — длина строки FASTA с учётом переноса
#
# Для нашего анализа нужны только NAME и LENGTH.

for line in fai_path.read_text().splitlines():

    # Пропускаем пустые строки.
    if not line.strip():
        continue

    # Разделяем строку по символам табуляции.
    columns = line.split("\t")

    # Извлекаем название и длину последовательности.
    contig = columns[0]
    length = columns[1]

    # Выводим результат в формате TSV.
    print(f"{contig}\t{length}")