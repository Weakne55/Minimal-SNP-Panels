#!/usr/bin/env bash

# ============================================================
# Запуск одной задачи WGS-пайплайна через SLURM Job Array
# ============================================================
#
# Этот скрипт автоматически вызывается SLURM для каждого
# элемента массива заданий (Job Array).
#
# Каждый элемент массива выполняет одну задачу пайплайна.
# Например, это может быть:
#   - картирование одного WGS-образца;
#   - вызов вариантов для одной хромосомы;
#   - совместное генотипирование одной хромосомы.
#
# Входные аргументы:
#   $1 — путь к JSON-файлу с планом выполнения пайплайна;
#   $2 — путь к текстовому файлу со списком идентификаторов задач.
#
# Скрипт:
#   1. Определяет номер текущего элемента SLURM Job Array.
#   2. Находит соответствующий идентификатор задачи.
#   3. Передаёт его основному Python-скрипту pipeline.py.
#
# Скрипт предназначен для запуска через SLURM, а не вручную.


# ============================================================
# 1. Настройки Bash
# ============================================================

# -e        Завершать скрипт при ошибке команды.
# -u        Считать ошибкой обращение к неопределённой переменной.
# -o pipefail
#           Считать конвейер команд неуспешным, если любая
#           из его команд завершилась с ошибкой.
set -euo pipefail


# ============================================================
# 2. Проверка аргументов командной строки
# ============================================================

# Скрипт принимает ровно два аргумента:
#   PLAN_JSON     — JSON-файл плана;
#   TASK_IDS_FILE — текстовый файл со списком задач.
#
# $# — количество переданных аргументов.
if [[ $# != 2 ]]; then

    echo "Usage: run_array.sh PLAN_JSON TASK_IDS_FILE" >&2
    exit 2

fi


# ============================================================
# 3. Получение номера задачи SLURM
# ============================================================

# SLURM_ARRAY_TASK_ID — переменная окружения, которую SLURM
# автоматически задаёт каждому элементу массива.
#
# Например, для массива --array=0-3:
#   первый элемент  -> SLURM_ARRAY_TASK_ID=0
#   второй элемент  -> SLURM_ARRAY_TASK_ID=1
#   третий элемент  -> SLURM_ARRAY_TASK_ID=2
#   четвёртый       -> SLURM_ARRAY_TASK_ID=3
#
# Если переменная не определена, скрипт завершится с ошибкой.
: "${SLURM_ARRAY_TASK_ID:?Must be executed inside a SLURM array}"


# ============================================================
# 4. Чтение входных аргументов
# ============================================================

# JSON-файл, содержащий полный план выполнения пайплайна.
plan=$1

# Текстовый файл со списком идентификаторов задач.
# Каждый идентификатор записан на отдельной строке.
task_list=$2


# ============================================================
# 5. Определение задачи текущего элемента массива
# ============================================================

# Нумерация элементов SLURM начинается с нуля.
# Нумерация строк в sed начинается с единицы.
#
# Поэтому для поиска нужной строки добавляем 1.
#
# Пример:
#   SLURM_ARRAY_TASK_ID=0 -> строка 1
#   SLURM_ARRAY_TASK_ID=1 -> строка 2
#   SLURM_ARRAY_TASK_ID=2 -> строка 3
line_number=$((SLURM_ARRAY_TASK_ID + 1))


# Получаем идентификатор задачи из соответствующей строки.
#
# sed -n "${line_number}p":
#   -n — отключить автоматический вывод строк;
#   Np — вывести только строку номер N.
#
# Например, если файл содержит:
#   align_sample1
#   align_sample2
#   align_sample3
#
# При SLURM_ARRAY_TASK_ID=1 будет выбран align_sample2.
task_id=$(sed -n "${line_number}p" "$task_list")


# ============================================================
# 6. Проверка найденной задачи
# ============================================================

# Если номер элемента массива выходит за пределы списка
# или соответствующая строка пуста, выполнить задачу нельзя.
if [[ -z "$task_id" ]]; then

    echo "No task for SLURM_ARRAY_TASK_ID=$SLURM_ARRAY_TASK_ID" >&2
    exit 1

fi


# ============================================================
# 7. Определение корневой директории проекта
# ============================================================

# BASH_SOURCE[0] — путь к текущему скрипту.
#
# dirname — директория, в которой находится run_array.sh.
#
# /.. — переход на один уровень выше, в корень WGS_GATK_simple.
#
# pwd — получение абсолютного пути к этой директории.
#
# Это позволяет находить pipeline.py независимо
# от текущей рабочей директории задания SLURM.
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"


# ============================================================
# 8. Запуск задачи через Python
# ============================================================

# PIPELINE_PYTHON — путь к Python-интерпретатору, переданный
# при отправке задания через sbatch.
#
# Если переменная отсутствует, используется python3 из PATH.
#
# Это позволяет использовать ту же среду Conda,
# из которой был запущен пайплайн.
#
# Команда run-task сообщает pipeline.py:
#   --plan    — где находится JSON-план;
#   --task-id — какую конкретно задачу выполнить.
#
# exec заменяет текущий процесс Bash процессом Python.
# Код завершения Python становится кодом завершения задания
# SLURM, что позволяет правильно учитывать успешность задачи.

exec "${PIPELINE_PYTHON:-python3}" "$root/scripts/pipeline.py" \
    run-task \
    --plan "$plan" \
    --task-id "$task_id"