#!/usr/bin/env bash

# Проверка наличия программ, необходимых для работы WGS-пайплайна.
# Скрипт выводит пути к найденным программам и проверяет наличие PyYAML,
# SLURM и Java.

set -euo pipefail


# ------------------------------------------------------------
# 1. Проверка основных программ
# ------------------------------------------------------------

# Список программ, необходимых для обработки WGS.
for program in python3 bwa-mem3 samtools bcftools gatk mosdepth multiqc; do

    # Проверяем, доступна ли программа через PATH.
    # Если программа отсутствует, выводим ошибку и завершаем скрипт.
    if ! command -v "$program" > /dev/null 2>&1; then
        echo "ERROR: программа $program не найдена" >&2
        exit 1
    fi

    # Выводим название программы и полный путь к исполняемому файлу.
    printf '%-10s %s\n' "$program" "$(command -v "$program")"

done


# ------------------------------------------------------------
# 2. Версия BWA-MEM3 и библиотека PyYAML
# ------------------------------------------------------------

# Версия aligner фиксируется в envs/wgs.yaml и сохраняется в логах.
bwa-mem3 version

# PyYAML используется для чтения конфигурации config.yaml.
# Если библиотека отсутствует, Python завершится с ошибкой.
python3 -c 'import yaml; print("PyYAML", yaml.__version__)'


# ------------------------------------------------------------
# 3. Проверка SLURM
# ------------------------------------------------------------

# sbatch необходим для запуска вычислительных задач через SLURM.
# Его отсутствие не препятствует локальному тестированию.
if command -v sbatch > /dev/null 2>&1; then
    echo "SLURM: sbatch найден"
else
    echo "SLURM: sbatch не найден (доступен только локальный запуск)"
fi


# ------------------------------------------------------------
# 4. Проверка версии Java
# ------------------------------------------------------------

# Java необходима для работы GATK.
# Показываем первые две строки информации о версии Java.
java -version 2>&1 | head -2